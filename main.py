def norm_name(t):
    t=unicodedata.normalize("NFD",t or "")
    t="".join(ch for ch in t if not unicodedata.combining(ch))
    t=re.sub(r"[^a-z0-9а-яё]+"," ",t.lower())
    return re.sub(r"\s+"," ",t).strip()

