def ask_qwen(images,user_text,model,timeout=120,attempts=2,use_system=True,temperature=None,tags=None):
    content=[]
    for i,b in enumerate(images):
        content.append({"type":"image_url","image_url":{"url":f"data:image/jpeg;base64,{b}"}})
        if tags and i<len(tags) and tags[i]:
            content.append({"type":"text","text":"фото %d: %s"%(i+1,tags[i])})
    content.append({"type":"text","text":user_text})
    messages=[]
    if use_system: messages.append({"role":"system","content":SYSTEM})
    messages.append({"role":"user","content":content})
    fallback=QWEN3_MODEL if model==QWEN_MODEL else QWEN_MODEL
    cur=model; fell=False
    r=None; attempt=0
    while attempt<attempts:
        body={"model":cur,"messages":messages}
        if temperature is not None: body["temperature"]=temperature
        try:
            r=requests.post(BASE+"/chat/completions",headers={"Authorization":"Bearer "+QWEN_KEY,"Content-Type":"application/json"},json=body,timeout=timeout)
        except requests.exceptions.RequestException as e:
            logging.error("QWEN NET %s",e)
            attempt+=1
            if attempt>=attempts: raise
            time.sleep(3); continue
        if r.status_code==429:
            logging.error("QWEN RETRY 429 %s",r.text[:500])
            ra=5
            try: ra=float((r.json().get("error",{}).get("metadata",{}) or {}).get("retry_after_seconds") or 5)
            except Exception: pass
            time.sleep(min(max(ra,5),30))
            if not fell:
                fell=True; cur=fallback
                logging.info("QWEN FALLBACK %s -> %s",model,cur)
                continue
            attempt+=1; continue
        if r.status_code in (500,502,503):
            logging.error("QWEN RETRY %s %s",r.status_code,r.text[:500])
            attempt+=1
            if attempt>=attempts: break
            time.sleep(4); continue
        break
    if r.status_code!=200:
        logging.error("QWEN ERROR %s %s",r.status_code,r.text[:1500])
    r.raise_for_status()
    d=r.json()
    if "choices" not in d or not d["choices"]:
        logging.error("QWEN NOCHOICES model=%s body=%s",cur,r.text[:800])
        time.sleep(4)
        body={"model":cur,"messages":messages}
        if temperature is not None: body["temperature"]=temperature
        r=requests.post(BASE+"/chat/completions",headers={"Authorization":"Bearer "+QWEN_KEY,"Content-Type":"application/json"},json=body,timeout=timeout)
        if r.status_code!=200:
            logging.error("QWEN ERROR %s %s",r.status_code,r.text[:1500])
            r.raise_for_status()
        d=r.json()
        if "choices" not in d or not d["choices"]:
            logging.error("QWEN NOCHOICES2 model=%s body=%s",cur,r.text[:800])
            raise ValueError("no choices")
    return d["choices"][0]["message"]["content"]

def downscale_b64(raw,limit):
    im=Image.open(io.BytesIO(raw)).convert("RGB")
    w,h=im.size; m=max(w,h)
    if m>limit:
        k=limit/m; im=im.resize((int(w*k),int(h*k)),Image.LANCZOS)
    buf=io.BytesIO(); im.save(buf,"JPEG",quality=85)
    return base64.b64encode(buf.getvalue()).decode()

def has_cam_exif(im):
    try:
        ex=im.getexif()
        return bool(ex.get(271) or ex.get(272))
    except Exception:
        return False

def img_b64(m):
    is_doc=m.content_type=="document"
    fid=m.photo[-1].file_id if not is_doc else m.document.file_id
    fp=bot.get_file(fid).file_path
    r=requests.get(f"https://api.telegram.org/file/bot{TOKEN}/{fp}",timeout=60)
    shot_flag=""
    if is_doc:
        size=len(r.content)
        fn=(m.document.file_name or "").lower()
        w=0; h=0; cam_exif=False
        try:
            im=Image.open(io.BytesIO(r.content))
            w,h=im.size
            cam_exif=has_cam_exif(im)
        except Exception:
            pass
        if ("screenshot" in fn or "скрин" in fn) or size<300*1024:
            shot_flag="hard"
        elif w*h and w*h<2_000_000:
            shot_flag="lowres"
        elif size<800*1024 and not cam_exif:
            shot_flag="soft"
        elif (w>0 and h>0 and 2.0<=h/w<=2.44) or (not cam_exif and size<1200*1024):
            shot_flag="model"
    return downscale_b64(r.content,2048 if is_doc else 1600), (not is_doc), shot_flag

