def parse_details(rep):
    d={}
    for line in rep.splitlines():
        m=re.match(r'^(0[1-5])\b',line.strip())
        if not m: continue
        st=next((e for e in ("❌","⚠️","➖","✅") if e in line),None)
        if st: d[m.group(1)]=st
    return d

def replace_detail(rep,n,newfirst):
    lines=rep.split("\n")
    start=None
    for i,l in enumerate(lines):
        if re.match(r"^\s*"+n+r"\b",l):
            start=i; break
    if start is None: return rep
    end=len(lines)
    for j in range(start+1,len(lines)):
        if re.match(r"^\s*0[1-5]\b",lines[j]) or lines[j].strip().startswith(TAIL_MARKERS):
            end=j; break
    lines[start]=newfirst
    del lines[start+1:end]
    return "\n".join(lines)

def detail_just(rep,n):
    out=[]
    started=False
    for l in rep.splitlines():
        if re.match(r"^\s*"+n+r"\b",l):
            started=True
            out.append(l)
            continue
        if started:
            if re.match(r"^\s*0[1-5]\b",l): break
            if l.strip().startswith(TAIL_MARKERS): break
            out.append(l)
    txt=" ".join(x.strip() for x in out)
    txt=re.sub(r"^\s*"+n+r"\s*(?:✅|⚠️|❌|➖)?\s*","",txt)
    txt=re.sub(r"^[^:：]*[:：]\s*","",txt)
    return txt[:300]

