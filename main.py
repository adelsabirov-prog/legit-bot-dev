def itemmap_demote(cid,rep,details):
    for n in [k for k,v in details.items() if v=="❌"]:
        mline=""
        for l in rep.splitlines():
            if re.match(r"^\s*"+n+r"\b",l):
                mline=l; break
        mi=re.search(r"п\.\s*(\d+)",mline)
        if not mi: continue
        item=mi.group(1)
        if item in ITEM_MAP and n not in ITEM_MAP[item]:
            newfirst=f"{n} ⚠️ {PDF_NAMES.get(n,'')}: маркер был указан по пункту {item}, который не относится к этой детали; статус снижен до сомнения."
            rep=replace_detail(rep,n,newfirst)
            details[n]="⚠️"
            logging.info("ITEMMAP cid=%s n=%s item=%s demoted",cid,n,item)
    return rep,details

