def catalog_match(t):
    k=norm_name(t)
    if not k: return None
    if k in CAT_INDEX: return CAT_INDEX[k]
    c=difflib.get_close_matches(k,CAT_KEYS,n=1,cutoff=0.85)
    return CAT_INDEX[c[0]] if c else None

