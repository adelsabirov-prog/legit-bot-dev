def ocr3_read(b64):
    if _ocr3 is None: return None
    try:
        import numpy as np
        im=Image.open(io.BytesIO(base64.b64decode(b64))).convert("RGB")
        arr=np.array(im)
        r,_=_ocr3(arr)
        if not r: return None
        txt="".join(line[1] for line in r)
        return txt.strip() or None
    except Exception:
        logging.exception("ocr3 read")
        return None

