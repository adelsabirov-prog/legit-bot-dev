@bot.message_handler(func=lambda m: m.content_type=="text" and not m.text.startswith("/"))
def text(m):
    cid=m.chat.id; s=st(cid); t=m.text.strip()
    if t.lower() in ("старт","начать","начать заново","заново"):
        reset(cid)
        return
    if t.lower() in ("отмена","стоп","cancel"):
        reset(cid)
        bot.send_message(cid,"Проверка отменена. Для новой — напишите «Начать заново».")
        return
    if t.lower()=="навыки бота":
        bot.send_message(cid,SKILLS_TEXT,reply_markup=types.ReplyKeyboardRemove())
        return
    if s["stage"]=="feedback":
        logging.warning("FEEDBACK DOWN %s: %s",cid,t)
        s["stage"]="done"
        update_case_meta(s,feedback="down")
        bot.send_message(cid,"Спасибо! Обратная связь записана и будет учтена.")
        return
    if s["stage"]=="recheck_photo":
        bot.send_message(cid,"📥 Жду фото этой детали документом.")
        return
    if s["stage"]=="pay":
        bot.send_message(cid,"Сначала оплатите выбранный тариф — или напишите «Начать заново».")
        return
    if s["stage"]=="recheck":
        num="".join(ch for ch in t if ch.isdigit())
        n=("0"+num) if len(num)==1 else num
        if n not in ("01","02","03","04","05"):
            bot.send_message(cid,"Напишите номер пункта от 01 до 05.")
            return
        do_recheck(cid,s,n,s["rc_photo"])
        return
    if s["stage"]=="name":
        low=t.lower()
        if "?" in t or low in ("привет","здравствуйте","добрый день","добрый вечер","хай","ку") or low.startswith(("что это","как работает","сколько стоит","цена","кто ты","что умеешь")):
            bot.send_message(cid,HELP_TEXT)
            return
        s["name"]=t
        logging.info("FUNNEL name cid=%s name=%s",cid,t)
        model=s.get("model") or QWEN_MODEL
        try:
            boxres=ask_qwen([],MODE_BOX.format(name=t),model,timeout=45,attempts=1,use_system=False,temperature=0)
        except Exception:
            logging.exception("mode_box")
            boxres="ФОРМ-ФАКТОР: флакон с распылителем\nНАЗВАНИЕ: "+t
        corrected=parse(boxres,"НАЗВАНИЕ") or t
        if corrected.lower()!=t.lower():
            s["name"]=corrected
            bot.send_message(cid,f"Принято: {corrected} (исправлено из «{t}»). Если неверно — напишите «Начать заново».")
        else:
            bot.send_message(cid,f"Принято: {t}.")
        s["ff"]=norm_ff(parse(boxres,"ФОРМ-ФАКТОР"))
        s["stage"]="box"
        bot.send_message(cid,"Что проверяем?",reply_markup=kb_obj())
        return
    if s["stage"]=="box":
        bot.send_message(cid,"Нажмите кнопку: «Флакон без коробки» или «Флакон с коробкой».")
        return
    if s["stage"]=="chain":
        low=t.lower()
        if s.get("pending",-1)>=0:
            if low in ("да","yes","ага","да, это"):
                ni=s["pending"]; b64=s["pending_b64"]
                accept_step(cid,s,ni+1,b64)
            else:
                s["pending"]=-1; s["pending_b64"]=""
                ni=first_open(s)
                if ni>=0:
                    bot.send_message(cid,"Хорошо, жду новый кадр.\n"+step_msg(s,ni))
            return
        if low in ("не получается","не вижу","не могу найти","плохо видно","не могу снять"):
            ni=first_open(s)
            if ni>=0:
                obj=s.get("obj") or "both"
                h=hint_for(s["queue"][ni],s.get("ff","default"),obj)
                bot.send_message(cid,"Подсказываю ещё раз по текущему шагу.\n"+h+"\nЕсли не получается — напишите «нет», и эта деталь не будет разбираться.")
            return
        if low in ("не могу","нет","без коробки","нет коробки"):
            s["retakes"]=0
            ni=first_open(s)
            if ni>=0:
                s["cannot"].append(s["queue"][ni])
                s["closed"].append(ni)
                s["last_closed"]=ni
            n2=first_open(s)
            if n2>=0:
                bot.send_message(cid,"Хорошо, пропускаю шаг, идём дальше.\n"+step_msg(s,n2))
            else:
                end_chain(cid)
            return
        if low in ("готово","done"):
            ni=first_open(s)
            if ni>=0:
                left="\n".join("%d. %s"%(i+1,s["queue"][i]) for i in range(len(s["queue"])) if i not in s["closed"])
                bot.send_message(cid,"Осталось собрать кадры:\n"+left+"\nПришлите фото или напишите «нет», если шага нет в вашем продукте.")
            else:
                end_chain(cid)
            return
        bot.send_message(cid,"Сейчас собираем кадры по шагам. Пришлите фото текущего шага (документом) или напишите «нет», если шага нет в вашем продукте.")
        return
    if s["stage"]=="tariffs":
        bot.send_message(cid,"Выберите тариф кнопками ниже. Если кнопки пропали — напишите «Начать заново».")
    elif s["stage"]=="done":
        bot.send_message(cid,"Отчёт выдан. Хотите перепроверить пункт — нажмите кнопку «Перепроверить» под отчётом или пришлите фото этого места документом. Для новой проверки напишите «Начать заново».")
    else:
        bot.send_message(cid,"Напишите «Начать заново», чтобы начать проверку.")

